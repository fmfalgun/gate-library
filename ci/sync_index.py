#!/usr/bin/env python3
"""Command-line entry for gate-library: validate, generate, explain, scaffold, log.

Single purpose: parse the command line and call the gate_lib modules in the
right order. All rules and output building live in ci/gate_lib.

    python ci/sync_index.py                      validate, then write api/v1 and the README rule list
    python ci/sync_index.py --check              validate and fail if generated files are stale (G20)
    python ci/sync_index.py --online             also check xrefs against other repos (warnings only)
    python ci/sync_index.py --explain SLUG       show an item's links and look-alike warnings
    python ci/sync_index.py --new KIND SLUG      create a file from the template
    python ci/sync_index.py --stats              print coverage and accuracy per paper
    python ci/sync_index.py --attempt SLUG RESULT [REASON]   append a dated attempt
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import gate_cli  # noqa: E402  (path set up above)
from gate_lib import coverage, emit, graph, parse, rules  # noqa: E402
from gate_lib.checks.xrefs import fetch_json  # noqa: E402
from gate_lib.config import ConfigError  # noqa: E402
from gate_lib.model import Finding  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent


def build_parser() -> argparse.ArgumentParser:
    """Define the command-line options; the modes are mutually exclusive."""
    parser = argparse.ArgumentParser(description="Validate and generate the gate-library index.")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="repo root (default: this repo)")
    parser.add_argument("--check", action="store_true", help="validate only; fail if api/v1 or README would change")
    parser.add_argument("--online", action="store_true", help="also verify xrefs over the network (warnings only)")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--explain", metavar="SLUG", help="print an item's links in both directions")
    mode.add_argument("--new", nargs=2, metavar=("KIND", "SLUG"), help="create a file from the template")
    mode.add_argument("--stats", action="store_true", help="print coverage and accuracy per paper")
    mode.add_argument("--attempt", nargs="+", metavar="ARG", help="SLUG RESULT [REASON]: append a dated attempt")
    return parser


def print_findings(findings: list[Finding]) -> None:
    """Print each finding on its own line to stderr so stdout stays clean."""
    for finding in findings:
        print(finding.render(), file=sys.stderr)


def _split(findings: list[Finding]) -> tuple[list[Finding], list[Finding]]:
    """Split findings into (errors, warnings)."""
    errors = [found for found in findings if found.severity == "error"]
    return errors, [found for found in findings if found.severity == "warning"]


def run_sync(root: Path, check_only: bool, online: bool) -> int:
    """Validate everything, then write (or with check_only, compare) the generated files.

    Returns 1 on any error or stale output, else 0. Online findings are
    printed but never change the exit code or the generated bytes.
    """
    try:
        repo = parse.load_repo(root)
    except ConfigError as problem:
        print(f"config error: {problem}", file=sys.stderr)
        return 1
    findings = rules.run_offline_checks(repo)
    errors, warnings = _split(findings)
    if not errors:
        outputs = emit.build_outputs(repo, findings)
        errors = emit.stale_findings(repo, outputs) if check_only else []
        if not check_only:
            emit.write_outputs(root, outputs)
    extra = rules.run_online_checks(repo, fetch_json) if online else []
    print_findings(errors + warnings + extra)
    return 1 if errors else 0


def explain(root: Path, slug: str) -> int:
    """Print one item's links (both directions) and the warnings that mention it. Returns 1 if unknown."""
    repo = parse.load_repo(root)
    item = repo.by_slug.get(repo.resolve(slug))
    if item is None or item.error:
        print(f"no item '{slug}'", file=sys.stderr)
        return 1
    print(f"{item.slug}  ({item.kind})  {item.data.get('title', '')}")
    for name, value in graph.compute_links(repo)[item.slug].items():
        print(f"  {name}: {value}")
    print_findings([found for found in rules.run_offline_checks(repo) if item.slug in found.slugs])
    return 0


def attempt(root: Path, arguments: list[str]) -> int:
    """Run --attempt: SLUG RESULT [REASON]. Returns 1 when the argument count is wrong."""
    if not 2 <= len(arguments) <= 3:
        print("usage: --attempt SLUG right|wrong|skipped [REASON]", file=sys.stderr)
        return 1
    return gate_cli.add_attempt(root, arguments[0], arguments[1], arguments[2] if len(arguments) == 3 else None)


def main(argv: list[str] | None = None) -> int:
    """Dispatch to the chosen mode and return the process exit code."""
    args = build_parser().parse_args(argv)
    if args.explain:
        return explain(args.root, args.explain)
    if args.new:
        return gate_cli.new_item(args.root, args.new[0], args.new[1])
    if args.attempt:
        return attempt(args.root, args.attempt)
    if args.stats:
        print(coverage.render_stats(parse.load_repo(args.root)))
        return 0
    return run_sync(args.root, args.check, args.online)


if __name__ == "__main__":
    sys.exit(main())
